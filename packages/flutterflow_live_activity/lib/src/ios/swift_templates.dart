/// Gives a compact region a fixed width that fits the system's compact
/// widths, so the island never sizes it to a different width from one home
/// page to the next and clips the ring or the digits. Content that is wider
/// shrinks instead of being cut, and a small inset keeps it off the island's
/// curved edge.
extension View {
  func ffCompactFit(width: CGFloat, alignment: Alignment) -> some View {
    self
      .lineLimit(1)
      .minimumScaleFactor(0.6)
      .frame(width: width, alignment: alignment)
      .padding(alignment == .leading ? .leading : .trailing, 2)
  }
}

