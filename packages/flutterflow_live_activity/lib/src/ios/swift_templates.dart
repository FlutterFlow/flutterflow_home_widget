/// The app side: the method channel over ActivityKit. With [imageTargets]
/// (`liveActivityImageTargets`, not empty when a Custom card has an Image
/// value) it also stores the pictures the calls bring.
String liveActivityPluginSwiftFor(Map<String, Map<String, int>> imageTargets) {
  final images = imageTargets.isNotEmpty;
  // What an image-carrying call does before and after its own work.
  String before(String wait, String why) =>
      images
          ? '''
        $why
        let loads = $_imageStore.load(
          images, definitionKey: definitionKey, instanceId: instanceId)
        let pictures = await $_imageStore.ready(loads, within: $wait)
        let values = values.merging(pictures) { _, new in new }
'''
          : '';
  final after =
      images
          ? '''
        // The pictures are on the card now; one that was not ready goes on
        // when it arrives. Then drop the pictures no card shows any more.
        $_imageStore.release(pictures.values)
        $_imageStore.late(
          loads, applied: pictures, definitionKey: definitionKey, instanceId: instanceId)
        $_imageStore.sweep()
'''
          : '';
  final launchSweep =
      images
          ? '''
    #if canImport(ActivityKit)
    if #available(iOS $_minIos, *) {
      // Pictures an earlier run left behind for cards that are gone.
      Task { @MainActor in $_imageStore.sweep() }
    }
    #endif
'''
          : '';
  final readImages =
      images
          ? '''
    // The pictures of Image values, by value key. They are stored where the
    // card can read them and the card's values get each one's name.
    let images = args["$_argImages"] as? [String: Any] ?? [:]
'''
          : '';
  return '''
