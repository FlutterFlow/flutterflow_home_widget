/// Time left until the end time. The system redraws it every second, so it
/// counts down without any update from the app.
struct FFCountdown: View {
  let card: FFCard

  var body: some View {
    if let end = card.endTime {
      Text(timerInterval: min(Date(), end)...end, countsDown: true)
        .monospacedDigit()
        .lineLimit(1)
    } else {
      Text("--:--")
        .monospacedDigit()
    }
  }
}

/// A bar that fills from the start time to the end time on its own.
struct FFTimerBar: View {
  let card: FFCard

  var body: some View {
    if let span = card.timerSpan {
      ProgressView(
        timerInterval: span,
        countsDown: false,
        label: { EmptyView() },
        currentValueLabel: { EmptyView() }
      )
      .tint(card.accent)
    }
  }
}

