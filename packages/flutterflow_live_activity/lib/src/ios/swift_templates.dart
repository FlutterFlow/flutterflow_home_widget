/// The iOS files of [app]'s Live Activities, path (relative to the app's
/// root) to content: the widget extension under `ios/LiveActivity/` and the
/// iOS side of the `ff_live_activity` plugin package. Names, channel and
/// keys come from `contract.dart`.
///
/// The fixed templates do not depend on the app: the template, the accent
/// colour and the icon of each activity travel in the start call, so one
/// widget draws every definition and a settings change never needs new
/// native code. Only Custom cards add code of their own.
Map<String, String> liveActivityIosFiles(LiveActivityApp app) {
  final custom = app.hasCustomCards;
  final imageTargets = liveActivityImageTargets(app);
  return {
    // Widget extension target. The pbxproj fragments list exactly these files.
    '$kLiveActivityIosExtensionPath/Info.plist': liveActivityExtensionInfoPlist(
      app,
    ),
    '$kLiveActivityIosExtensionPath/$kLiveActivityIosBundleSwiftFile':
        custom
            ? liveActivityCustomWidgetBundleSwift
            : liveActivityWidgetBundleSwift,
    // The Custom cards' views, written from their layouts.
    if (custom)
      '$kLiveActivityIosExtensionPath/$kLiveActivityIosCardsSwiftFile':
          liveActivityCardsSwift(app),
    // The keychain group the extension reads Image values' pictures from.
    if (imageTargets.isNotEmpty)
      '$kLiveActivityIosExtensionPath/$kLiveActivityIosEntitlementsFile':
          liveActivityExtensionEntitlements(app),
    '$kLiveActivityIosExtensionPath/$kLiveActivityIosAttributesSwiftFile':
        liveActivityAttributesSwift,
    // iOS side of the plugin package.
    '$kLiveActivityIosPluginPath/$_package.podspec': kLiveActivityPodspec,
    '$kLiveActivityIosPluginPath/$_package/Package.swift':
        kLiveActivityPackageSwift,
    '$kLiveActivityIosPluginSourcesPath/$_plugin.swift':
        imageTargets.isEmpty
            ? liveActivityPluginSwift
            : liveActivityPluginSwiftFor(imageTargets),
    '$kLiveActivityIosPluginSourcesPath/$kLiveActivityIosAttributesSwiftFile':
        liveActivityAttributesSwift,
  };
}

