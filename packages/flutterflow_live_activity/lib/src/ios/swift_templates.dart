/// One card as a template reads it: the fixed attributes plus the typed view
/// of the string values. A missing or unreadable value shows as empty, never
/// as an error.
struct FFCard {
  /// nil for a template this version of the app does not know: the card then
  /// shows its title and status line only.
  let template: FFTemplate?
  let accent: Color
  let icon: UIImage?
  let values: [String: String]

  init(_ attributes: $_attributes, _ state: $_attributes.ContentState) {
    template = FFTemplate(rawValue: attributes.template)
    accent = Color(ffHex: attributes.accentColor) ?? FFCard.defaultAccent
    icon = FFIconLoader.image(bundlePath: attributes.icon)
    values = state.values
  }

  static let defaultAccent = Color(red: 0.26, green: 0.52, blue: 0.96)

  private func string(_ key: String) -> String { values[key] ?? "" }
  private func int(_ key: String) -> Int? { Int(values[key] ?? "") }
  private func double(_ key: String) -> Double? { Double(values[key] ?? "") }
  /// Milliseconds since the Unix epoch.
  private func date(_ key: String) -> Date? {
    guard let millis = Double(values[key] ?? "") else { return nil }
    return Date(timeIntervalSince1970: millis / 1000)
  }

  var title: String { string("$kLiveActivityValueTitle") }
  var statusText: String { string("$kLiveActivityValueStatusText") }
  /// 0 to 1.
  var progress: Double { min(max(double("$kLiveActivityValueProgress") ?? 0, 0), 1) }
  var endTime: Date? { date("$kLiveActivityValueEndTime") }
  var startTime: Date? { date("$kLiveActivityValueStartTime") }
  var homeName: String { string("$kLiveActivityValueHomeName") }
  var homeScore: Int? { int("$kLiveActivityValueHomeScore") }
  var awayName: String { string("$kLiveActivityValueAwayName") }
  var awayScore: Int? { int("$kLiveActivityValueAwayScore") }
  var position: Int? { int("$kLiveActivityValuePosition") }
  var estimatedWaitMinutes: Int? { int("$kLiveActivityValueEstimatedWaitMinutes") }

  /// The span the timer bar fills, when the card has a start time before its
  /// end time.
  var timerSpan: ClosedRange<Date>? {
    guard let start = startTime, let end = endTime, start < end else { return nil }
    return start...end
  }
}

extension Color {
  /// `#AARRGGBB`.
  init?(ffHex: String?) {
    guard let hex = ffHex, hex.hasPrefix("#"), hex.count == 9,
      let argb = UInt32(hex.dropFirst(), radix: 16)
    else { return nil }
    self.init(
      .sRGB,
      red: Double((argb >> 16) & 0xFF) / 255,
      green: Double((argb >> 8) & 0xFF) / 255,
      blue: Double(argb & 0xFF) / 255,
      opacity: Double((argb >> 24) & 0xFF) / 255
    )
  }
}

/// Loads the card's icon from the host app's bundle: the image asset the
/// activity names, or the app icon when it names none.
enum FFIconLoader {
  /// `<App>.app`, two levels above `<App>.app/PlugIns/$_target.appex`.
  static var appBundleURL: URL {
    Bundle.main.bundleURL.deletingLastPathComponent().deletingLastPathComponent()
  }

  static func image(bundlePath: String?) -> UIImage? {
    var candidates: [URL] = []
    if let path = bundlePath, !path.isEmpty {
      candidates.append(appBundleURL.appendingPathComponent(path))
    }
    candidates.append(contentsOf: appIconURLs)
    for url in candidates {
      if let image = UIImage(contentsOfFile: url.path) {
        // A Live Activity cannot draw an image larger than itself.
        return image.preparingThumbnail(of: CGSize(width: 120, height: 120)) ?? image
      }
    }
    return nil
  }

  private static var appIconURLs: [URL] {
    guard
      let info = NSDictionary(contentsOf: appBundleURL.appendingPathComponent("Info.plist")),
      let icons = info["CFBundleIcons"] as? [String: Any],
      let primary = icons["CFBundlePrimaryIcon"] as? [String: Any],
      let files = primary["CFBundleIconFiles"] as? [String]
    else { return [] }
    return files.reversed().flatMap { name in
      ["@3x.png", "@2x.png", ".png"].map { suffix in
        appBundleURL.appendingPathComponent(name + suffix)
      }
    }
  }
}

