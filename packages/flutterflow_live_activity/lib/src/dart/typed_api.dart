/// The typed Dart API of an app's Live Activities: one class per activity
/// that starts, updates and ends it over the plugin's `FFLiveActivity`,
/// with a typed parameter per value and what the spec fixes (template,
/// accent color, icon, Android channel, defaults) filled in. The wire is
/// the plugin's, unchanged.
library;

import 'package:flutterflow_live_activity/src/contract.dart';
import 'package:flutterflow_live_activity/src/spec.dart';
import 'package:flutterflow_native_layout/flutterflow_native_layout.dart';

/// Path of the typed API library in the app: a second library of the
/// plugin package.
const kLiveActivityTypedApiPath =
    '$kLiveActivityPluginPackagePath/lib/live_activities.dart';

/// The app's import of the typed API.
const kLiveActivityTypedApiImport =
    'package:$kLiveActivityPluginPackage/live_activities.dart';

/// The typed API's files, path (relative to the app's root) to content.
///
/// Not part of [generateLiveActivityFiles], which is what an app whose
/// calls are generated for it needs; an app that calls the plugin by hand
/// adds this (the command line's `generate` and `apply` do).
Map<String, String> liveActivityTypedApiFiles(LiveActivityApp app) => {
  kLiveActivityTypedApiPath: liveActivityTypedApiLibrary(app),
};

/// The Dart class of each activity of [app], by activity key, in order:
/// the key in UpperCamelCase and `LiveActivity` (`delivery` ->
/// `DeliveryLiveActivity`). A name another activity has already taken gets
/// a number.
Map<String, String> liveActivityDartClassNames(LiveActivityApp app) {
  final taken = <String>{};
  return {
    for (final activity in app.activities)
      activity.key: _unique(liveActivityDartClassName(activity.key), taken),
  };
}

/// The Dart parameter of each value of [activity], by value key, in order:
/// the key in lowerCamelCase (`status_text` -> `statusText`), with `Value`
/// after a reserved word. A name another value has already taken gets a
/// number.
Map<String, String> liveActivityDartValueNames(
  LiveActivityDefinition activity,
) {
  final taken = {..._kOwnParameters};
  return {
    for (final key in _valueKeys(activity))
      key: _unique(liveActivityDartValueName(key), taken),
  };
}

/// [key] as a Dart parameter name, before any clash with another is
/// settled: see [liveActivityDartValueNames].
String liveActivityDartValueName(String key) {
  final words = _words(key);
  if (words.isEmpty) {
    return 'value';
  }
  final first = words.first;
  final name =
      [
        first == first.toUpperCase()
            ? first.toLowerCase()
            : first[0].toLowerCase() + first.substring(1),
        for (final word in words.skip(1)) _capitalized(word),
      ].join();
  if (RegExp('^[0-9]').hasMatch(name)) {
    return 'v$name';
  }
  return _kReserved.contains(name) || _kOwnParameters.contains(name)
      ? '${name}Value'
      : name;
}

/// `lib/live_activities.dart` of the plugin package: [kLiveActivityTypedApiPath].
String liveActivityTypedApiLibrary(LiveActivityApp app) {
  final classNames = liveActivityDartClassNames(app);
  final colors = app.activities.any(
    (activity) =>
        activity.isCustom &&
        activity.values.any((v) => v.type == LiveActivityValueType.color),
  );
  final out =
      StringBuffer()
        ..writeln(
          '// Generated by flutterflow_live_activity from the app\'s Live '
          'Activity spec.',
        )
        ..writeln('// Do not edit: generate and apply write it again.')
        ..writeln()
        ..writeln(
          '/// One class per Live Activity of the app. Each starts, updates and '
          'ends',
        )
        ..writeln(
          '/// its card with [$kLiveActivityDartClass], with a parameter per '
          'value and the',
        )
        ..writeln(
          "/// rest (template, accent color, icon, Android channel, defaults) "
          'from the',
        )
        ..writeln('/// spec.')
        ..writeln('library;')
        ..writeln();
  if (colors) {
    out.writeln("import 'dart:ui' show Color;");
    out.writeln();
  }
  out
    ..writeln("import '$kLiveActivityPluginPackage.dart';")
    ..writeln()
    ..write(_dismissalEnum);
  for (final activity in app.activities) {
    out
      ..writeln()
      ..write(_activityClass(activity, classNames[activity.key]!));
  }
  return out.toString();
}

/// What [_activityClass] names itself: a value named so gets `Value`.
const _kOwnParameters = {'instanceId', 'dismissal', 'definitionKey'};

/// Dart's reserved words, and the built-in identifiers that cannot name a
/// parameter safely.
const _kReserved = {
  'assert',
  'await',
  'break',
  'case',
  'catch',
  'class',
  'const',
  'continue',
  'default',
  'do',
  'else',
  'enum',
  'extends',
  'false',
  'final',
  'finally',
  'for',
  'if',
  'in',
  'is',
  'new',
  'null',
  'required',
  'rethrow',
  'return',
  'super',
  'switch',
  'this',
  'throw',
  'true',
  'try',
  'var',
  'void',
  'when',
  'while',
  'with',
  'yield',
};

List<String> _words(String key) =>
    key.split(RegExp('[^A-Za-z0-9]+')).where((w) => w.isNotEmpty).toList();

String _capitalized(String word) => word[0].toUpperCase() + word.substring(1);

/// [key] as a Dart class name, before any clash with another is settled:
/// see [liveActivityDartClassNames].
String liveActivityDartClassName(String key) {
  final name = _words(key).map(_capitalized).join();
  return name.isEmpty || RegExp('^[0-9]').hasMatch(name)
      ? 'LiveActivity$name'
      : '${name}LiveActivity';
}

String _unique(String name, Set<String> taken) {
  var unique = name;
  for (var n = 2; !taken.add(unique); n++) {
    unique = '$name$n';
  }
  return unique;
}

/// The keys of [activity]'s values: a Custom card's own, or its template's.
List<String> _valueKeys(LiveActivityDefinition activity) =>
    activity.isCustom
        ? [for (final value in activity.values) value.key]
        : [for (final value in activity.template.fixedValues) value.key];

/// A Dart string literal of [text].
String _dartString(String text) =>
    "'${escapeEach(text, const {"\\": r"\\", "'": r"\'", r"$": r"\$", "\n": r"\n", "\r": r"\r", "\t": r"\t"})}'";

/// [text] on one line, for a doc comment.
String _oneLine(String text) =>
    escapeEach(text.trim(), const {'\n': ' ', '\r': ' '});

const _dismissalEnum = '''
/// How an ended card leaves the screen.
enum LiveActivityDismissal {
  /// Right away.
  immediate('$kLiveActivityDismissalImmediate'),

  /// When the system removes it.
  systemDefault('$kLiveActivityDismissalSystemDefault');

  const LiveActivityDismissal(this.wireName);

  /// What the plugin sends.
  final String wireName;
}
''';

/// One parameter of a typed method: its Dart name and type, the wire key,
/// and the Dart expression of its wire value (or its image entry).
class _Param {
  const _Param(this.name, this.type, this.key, this.code, {this.image = false});

  final String name;
  final String type;
  final String key;
  final String code;
  final bool image;
}

List<_Param> _params(LiveActivityDefinition activity) {
  final names = liveActivityDartValueNames(activity);
  const cls = kLiveActivityDartClass;
  if (!activity.isCustom) {
    return [
      for (final value in activity.template.fixedValues)
        switch (value.type) {
          LiveActivityWireType.string => _Param(
            names[value.key]!,
            'String',
            value.key,
            names[value.key]!,
          ),
          LiveActivityWireType.double => _Param(
            names[value.key]!,
            'double',
            value.key,
            '$cls.$kLiveActivityEncodeDouble(${names[value.key]})',
          ),
          LiveActivityWireType.int => _Param(
            names[value.key]!,
            'int',
            value.key,
            '$cls.$kLiveActivityEncodeInt(${names[value.key]})',
          ),
          LiveActivityWireType.epochMillis => _Param(
            names[value.key]!,
            'DateTime',
            value.key,
            '$cls.$kLiveActivityEncodeDateTime(${names[value.key]})',
          ),
        },
    ];
  }
  return [
    for (final value in activity.values)
      _Param(
        names[value.key]!,
        switch (value.type) {
          LiveActivityValueType.string => 'String',
          LiveActivityValueType.integer => 'int',
          LiveActivityValueType.double => 'double',
          LiveActivityValueType.boolean => 'bool',
          LiveActivityValueType.dateTime => 'DateTime',
          LiveActivityValueType.color => 'Color',
          LiveActivityValueType.image => 'Object',
        },
        value.key,
        switch (value.type.encoder) {
          null when value.type == LiveActivityValueType.image =>
            '$cls.$kLiveActivityEncodeImage(${names[value.key]})',
          null => names[value.key]!,
          final encoder => '$cls.$encoder(${names[value.key]})',
        },
        image: value.type == LiveActivityValueType.image,
      ),
  ];
}

/// The values whose start has a default: each value's own (not an
/// image's, which the native side draws), and the start time of a bar that
/// fills between two dates on its own, which without one is the moment the
/// card starts.
Map<String, String> _defaults(LiveActivityDefinition activity) {
  final timedStarts = {
    for (final (_, model) in activity.layouts)
      for (final node in model.nodes)
        if (node case LayoutProgress(:final timedStart?)) timedStart,
  };
  return {
    for (final value in activity.values)
      if (value.type != LiveActivityValueType.image)
        if (value.defaultValue case final defaultValue?)
          value.key: _dartString(defaultValue)
        else if (value.type == LiveActivityValueType.dateTime &&
            timedStarts.contains(value.key))
          value.key: 'DateTime.now().millisecondsSinceEpoch.toString()',
  };
}

String _activityClass(LiveActivityDefinition activity, String className) {
  const cls = kLiveActivityDartClass;
  final params = _params(activity);
  final required = {
    for (final value in activity.values)
      if (value.required) value.key,
  };
  final defaults =
      activity.isCustom ? _defaults(activity) : const <String, String>{};

  String declarations({required bool start}) => [
    '    String? instanceId,',
    for (final param in params)
      start && required.contains(param.key)
          ? '    required ${param.type} ${param.name},'
          : '    ${param.type}? ${param.name},',
  ].join('\n');

  String map(Iterable<String> entries) =>
      entries.isEmpty
          ? ''
          : '{\n${entries.map((e) => '      $e,').join('\n')}\n    }';
  final values = map([
    for (final param in params)
      if (!param.image) '${_dartString(param.key)}: ${param.code}',
  ]);
  final images = map([
    for (final param in params)
      if (param.image) '${_dartString(param.key)}: ${param.code}',
  ]);
  final defaultsMap = map([
    for (final MapEntry(:key, :value) in defaults.entries)
      '${_dartString(key)}: $value',
  ]);

  String arguments(List<String?> lines) =>
      lines.whereType<String>().map((line) => '    $line,').join('\n');
  final common = ['definitionKey: definitionKey', 'instanceId: instanceId'];

  final doc =
      StringBuffer()
        ..writeln(
          '/// ${_oneLine(activity.name.isEmpty ? activity.key : activity.name)}'
          '${activity.description.trim().isEmpty ? '' : ': ${_oneLine(activity.description)}'}',
        )
        ..writeln('///')
        ..writeln(
          activity.isCustom
              ? '/// A Custom card.'
              : '/// The ${activity.template.wireName} template.',
        );
  if (params.isNotEmpty) {
    doc
      ..writeln('///')
      ..writeln('/// Values:');
    for (final param in params) {
      final value = activity.value(param.key);
      final notes = [
        if (value != null && value.name.isNotEmpty && value.name != param.key)
          value.name,
        if (required.contains(param.key)) 'required on start',
        if (defaults[param.key] case final d?)
          d.startsWith("'") ? 'default $d' : 'default: when it starts',
        if (param.image)
          'a picture: a web address, a file path, an asset or bytes',
      ];
      doc.writeln(
        '/// - [${param.name}] (`${_oneLine(param.key)}`)'
        '${notes.isEmpty ? '' : ': ${_oneLine(notes.join('; '))}'}',
      );
    }
  }

  return '''
${doc}abstract final class $className {
  /// The key the plugin knows the activity by.
  static const definitionKey = ${_dartString(activity.key)};

  /// Starts the card. Returns false when the device cannot show it.
  ///
  /// [instanceId] tells apart several cards of this activity side by side;
  /// without it there is one card, and starting again replaces it. A value
  /// left null shows its default.
  static Future<bool> start({
${declarations(start: true)}
  }) => $cls.$kLiveActivityMethodStart(
${arguments([...common, 'template: ${_dartString(activity.template.wireName)}', if (activity.accentColor case final color?) 'accentColor: ${_dartString(color)}', if (activity.icon case final icon?) 'icon: ${_dartString(icon)}', if (activity.androidChannelName.isNotEmpty) 'androidChannelName: ${_dartString(activity.androidChannelName)}', if (values.isNotEmpty) 'values: $values', if (defaultsMap.isNotEmpty) '$kLiveActivityDartArgDefaults: $defaultsMap', if (images.isNotEmpty) '$kLiveActivityArgImages: $images'])}
  );

  /// Changes the values that are not null on the running card and keeps
  /// the rest. Returns false when no such card is running.
  static Future<bool> update({
${declarations(start: false)}
  }) => $cls.$kLiveActivityMethodUpdate(
${arguments([...common, if (values.isNotEmpty) 'values: $values', if (images.isNotEmpty) '$kLiveActivityArgImages: $images'])}
  );

  /// Ends the running card, showing the values given last. Ending a card
  /// that is not running does nothing.
  static Future<void> end({
${declarations(start: false)}
    LiveActivityDismissal dismissal = LiveActivityDismissal.immediate,
  }) => $cls.$kLiveActivityMethodEnd(
${arguments([...common, if (values.isNotEmpty) 'values: $values', if (images.isNotEmpty) '$kLiveActivityArgImages: $images', 'dismissal: dismissal.wireName'])}
  );
}
''';
}
