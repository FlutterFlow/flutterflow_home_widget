            if (definition.configurable) FFHomeWidgetStore.choiceOf(ctx, id) else null
        }
        for ((choice, copies) in byChoice) {
            val values = FFHomeWidgetChoices.values(ctx, definition, choice)
            render(ctx, manager, copies.toIntArray(), definition, values)
