/// Asks which choice a widget shows as it is placed, and again when a person
/// reconfigures it (Android 12+). Leaving without one doesn't place it.
const _kotlinConfigureActivity =
    '''
package $_pkg

import android.app.Activity
import android.app.AlertDialog
import android.appwidget.AppWidgetManager
import android.content.Intent
import android.os.Bundle

class FFHomeWidgetConfigureActivity : Activity() {
    override fun onCreate(savedInstanceState: Bundle?) {
        super.onCreate(savedInstanceState)
        val id = intent?.extras?.getInt(
            AppWidgetManager.EXTRA_APPWIDGET_ID,
            AppWidgetManager.INVALID_APPWIDGET_ID,
        ) ?: AppWidgetManager.INVALID_APPWIDGET_ID
        setResult(RESULT_CANCELED, Intent().putExtra(AppWidgetManager.EXTRA_APPWIDGET_ID, id))
        val provider = AppWidgetManager.getInstance(this).getAppWidgetInfo(id)?.provider?.className
        val definition = FFHomeWidgetDefinitions.all.values.firstOrNull { it.provider.name == provider }
        if (definition == null) {
            finish()
            return
        }
        val choices = FFHomeWidgetChoices.all(this, definition)
        val builder = AlertDialog.Builder(this, R.style.FFHomeWidgetConfigureDialog)
            .setTitle(definition.choiceTitle)
            .setOnCancelListener { finish() }
        if (choices.isEmpty()) {
            builder.setMessage(R.string.ff_home_widget_no_choices)
                .setPositiveButton(android.R.string.ok) { _, _ -> done(id, definition, null) }
        } else {
            val current = FFHomeWidgetStore.choiceOf(this, id)
            val checked = choices.indexOfFirst { it.first == current }
            builder.setSingleChoiceItems(choices.map { it.second }.toTypedArray(), checked) { dialog, which ->
                dialog.dismiss()
                done(id, definition, choices[which].first)
            }
        }
        builder.show()
    }

    private fun done(id: Int, definition: FFHomeWidgetDefinition, choice: String?) {
        FFHomeWidgetStore.choose(this, id, choice)
        val manager = AppWidgetManager.getInstance(this)
        FFHomeWidgetRenderer.render(this, manager, intArrayOf(id), definition.key)
        // A URL that reads the choice's values fetched nothing for it yet:
        // the copy fetched when it was placed, before it had a choice.
        if (definition.refresh?.keys?.isNotEmpty() == true) {
            val ctx = applicationContext
            Thread {
                if (FFHomeWidgetFetcher.fetch(ctx, definition, choice)) {
                    FFHomeWidgetRenderer.render(ctx, manager, intArrayOf(id), definition.key)
                }
            }.start()
        }
        setResult(RESULT_OK, Intent().putExtra(AppWidgetManager.EXTRA_APPWIDGET_ID, id))
        finish()
    }
}
''';

