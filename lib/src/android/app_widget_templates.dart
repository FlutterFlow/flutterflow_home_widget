                val found = walk(json, value.path) ?: continue
                convert(found, value.type)?.let { values[value.key] = it }
            }
            FFHomeWidgetStore.write(ctx, target, values)
        } catch (e: Exception) {
            false
        } finally {
            connection?.disconnect()
        }
