/// Cells of each size, and the size in dp Android documents for that many
/// cells (`73n - 16`).
(int, int) _cells(HomeWidgetSize size) => switch (size) {
  HomeWidgetSize.medium => (4, 2),
  HomeWidgetSize.large => (4, 4),
  _ => (2, 2),
};

int _dp(int cells) => 73 * cells - 16;

String _providerInfo(HomeWidgetDefinition definition) {
  final sizes = [for (final (size, _) in definition.homeScreenLayouts) size];
  final (minW, minH) = _cells(sizes.first);
  var (maxW, maxH) = (minW, minH);
  for (final size in sizes) {
    final (w, h) = _cells(size);
    if (w > maxW) maxW = w;
    if (h > maxH) maxH = h;
  }
  final resize = [if (maxW > minW) 'horizontal', if (maxH > minH) 'vertical'];
  final previewTag = '${definition.androidResourceKey}_${sizes.first.tag}';
  return '''
<?xml version="1.0" encoding="utf-8"?>
<appwidget-provider xmlns:android="http://schemas.android.com/apk/res/android"
    android:description="@string/ff_home_widget_description_${definition.androidResourceKey}"
    android:initialLayout="@layout/ff_home_widget_placeholder"
    android:previewLayout="@layout/hw_layout_$previewTag"
    android:minWidth="${_dp(minW)}dp"
    android:minHeight="${_dp(minH)}dp"
    android:minResizeWidth="${_dp(minW)}dp"
    android:minResizeHeight="${_dp(minH)}dp"
    android:targetCellWidth="$minW"
    android:targetCellHeight="$minH"
    android:resizeMode="${resize.isEmpty ? 'none' : resize.join('|')}"
    android:updatePeriodMillis="${(definition.refresh?.intervalMinutes ?? 0) * 60000}"${definition.isConfigurable ? '\n    android:configure="$_pkg.FFHomeWidgetConfigureActivity"\n    android:widgetFeatures="reconfigurable"' : ''}
    android:widgetCategory="home_screen" />
''';
}

