/// The Android files of the feature, path (relative to the app's root) to
/// content: the Android side of the `ff_home_widget` plugin package. Its
/// manifest declares one AppWidgetProvider per definition, merged into the
/// app manifest by the Android Gradle plugin, so the app's own files need no
/// edit. Each size's layout is compiled by `remote_views_emitter.dart`.
///
/// The Kotlin below avoids `$` string templates (it concatenates instead), so
/// `$` in this file always means a Dart interpolation.
Map<String, String> homeWidgetAndroidFiles(HomeWidgetApp app) {
  // Android has no Lock Screen widgets: only the Home Screen layouts, and
  // only the widgets that have one.
  final definitions = app.androidWidgets;
  final kotlinDir = '$_root/src/main/kotlin/${_pkg.split('.').join('/')}';
  final layoutFiles = <String, String>{};
  final colors = <String, LayoutColor>{};
  final binders = StringBuffer();
  final layoutsByDefinition = <String, Map<HomeWidgetSize, String>>{};
  for (final definition in definitions) {
    final resourceKey = definition.androidResourceKey;
    for (final (size, model) in definition.homeScreenLayouts) {
      final tag = '${resourceKey}_${size.tag}';
      final compiled = remoteViewsLayout(
        tag,
        model,
        defaults: definition.defaultValues,
        widgetKey: definition.key,
      );
      layoutFiles['$_res/layout/${compiled.layoutName}.xml'] = compiled.xml;
      for (final MapEntry(:key, :value) in compiled.drawables.entries) {
        layoutFiles['$_res/drawable/$key.xml'] = value;
      }
      colors.addAll(compiled.colors);
      binders.write(compiled.binder);
      (layoutsByDefinition[definition.key] ??= {})[size] = kotlinBinderName(
        tag,
      );
    }
  }
  return {
    '$_root/build.gradle': _buildGradle(),
    '$_root/src/main/AndroidManifest.xml': _manifest(definitions),
    '$kotlinDir/$kHomeWidgetPluginClass.kt': _kotlinPlugin(),
    '$kotlinDir/FFHomeWidgetRenderer.kt': _kotlinRenderer(),
    '$kotlinDir/FFHomeWidgetOpenActivity.kt': _kotlinOpenActivity,
    '$kotlinDir/FFHomeWidgetButtonReceiver.kt': _kotlinButtonReceiver,
    '$kotlinDir/FFHomeWidgetConfigureActivity.kt': _kotlinConfigureActivity,
    '$kotlinDir/FFHomeWidgetDefinitions.kt': homeWidgetKotlinDefinitions(
      definitions,
      layoutsByDefinition,
    ),
    '$kotlinDir/FFHomeWidgetLayouts.kt':
        '''
// Generated by FlutterFlow from each home screen widget's layouts.
package $_pkg

import android.content.Context
import android.view.View
import android.widget.RemoteViews
$binders
''',
    '$_res/values/ff_home_widget_strings.xml': _strings(definitions),
    '$_res/values/ff_home_widget_colors.xml': _colors(colors, night: false),
    '$_res/values-night/ff_home_widget_colors.xml': _colors(
      colors,
      night: true,
    ),
    '$_res/values/ff_home_widget_styles.xml': _styles(night: false),
    '$_res/values-night/ff_home_widget_styles.xml': _styles(night: true),
    '$_res/values/ff_home_widget_dimens.xml': _dimens(v31: false),
    '$_res/values-v31/ff_home_widget_dimens.xml': _dimens(v31: true),
    '$_res/drawable/ff_home_widget_background.xml': _background,
    '$_res/layout/ff_home_widget_placeholder.xml': _placeholderLayout,
    ...layoutFiles,
    for (final definition in definitions)
      '$_res/xml/ff_home_widget_info_${definition.androidResourceKey}.xml':
          _providerInfo(definition),
  };
}

