String _xmlText(String value) => escapeEach(value, kAndroidXmlTextEscapes);

String _strings(List<HomeWidgetDefinition> definitions) {
  final lines = <String>[];
  for (final definition in definitions) {
    final key = definition.androidResourceKey;
    lines
      ..add(
        '    <string name="ff_home_widget_name_$key">'
        '${_xmlText(definition.displayName)}</string>',
      )
      ..add(
        '    <string name="ff_home_widget_description_$key">'
        '${_xmlText(definition.description.trim())}</string>',
      );
  }
  // Shown by the picker of a widget the app adds the choices to, before it
  // has added any.
  lines.add(
    '    <string name="ff_home_widget_no_choices">${_xmlText(kHomeWidgetNoChoicesText)}</string>',
  );
  return '''
<?xml version="1.0" encoding="utf-8"?>
<resources>
${lines.join('\n')}
</resources>
''';
}

