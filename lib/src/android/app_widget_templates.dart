/// `FFHomeWidgetDefinitions.kt`: the project's widgets, the binder of each
/// size's layout, and one provider class per widget (Android names a placed
/// widget by its provider class).
/// The Kotlin `refresh = FFHomeWidgetRefresh(...)` argument of [plan], or
/// nothing.
String _kotlinRefresh(HomeWidgetRefreshPlan? plan, List<String> keys) {
  if (plan == null) {
    return '';
  }
  final headers = plan.headers.entries
      .map((e) => '${kotlinString(e.key)} to ${kotlinString(e.value)}')
      .join(', ');
  final values = [
    for (final value in plan.values)
      'FFFetchedValue(${kotlinString(value.key)}, '
          '"${_fetchedType(value.type)}", listOf(${value.path.map((step) => switch (step) {
            JsonKey(:final name) => kotlinString(name),
            JsonIndex(:final index) => '$index',
          }).join(', ')}))',
  ];
  final keysCode = keys.isEmpty
      ? ''
      : ', listOf(${keys.map(kotlinString).join(', ')})';
  return '\n            refresh = FFHomeWidgetRefresh(${kotlinString(plan.url)}, '
      'mapOf($headers), listOf(${values.join(', ')})$keysCode),';
}

/// The native name of a fetched value's type.
String _fetchedType(HomeWidgetValueType type) => switch (type) {
  HomeWidgetValueType.integer => 'integer',
  HomeWidgetValueType.double => 'double',
  HomeWidgetValueType.boolean => 'bool',
  HomeWidgetValueType.dateTime => 'date',
  HomeWidgetValueType.color => 'color',
  HomeWidgetValueType.string => 'text',
};

/// The Kotlin `choiceTitle`, `choices` and `appChoices` arguments of
/// [definition], or nothing when a person picks nothing.
String _kotlinChoices(HomeWidgetDefinition definition) {
  final configuration = definition.configuration;
  if (configuration == null || !definition.isConfigurable) {
    return '';
  }
  String map(Map<String, String> values) =>
      'mapOf(${values.entries.map((e) => '${kotlinString(e.key)} to ${kotlinString(e.value)}').join(', ')})';
  final choices = [
    for (final choice in configuration.choices)
      'FFHomeWidgetChoice(${kotlinString(choice.id)}, '
          '${kotlinString(choice.name)}, '
          '${map(definition.choiceValues(choice))})',
  ];
  return '\n            choiceTitle = ${kotlinString(definition.choiceTitle)},'
      '\n            choices = listOf(${choices.join(', ')}),'
      '\n            appChoices = ${configuration.appChoices},';
}

String homeWidgetKotlinDefinitions(
  List<HomeWidgetDefinition> definitions,
  Map<String, Map<HomeWidgetSize, String>> layouts,
) {
  final entries = <String>[];
  final classes = <String>[];
  for (final definition in definitions) {
    final provider = definition.androidProviderClass;
    final key = kotlinString(definition.key);
    final defaults = definition.defaultValues;
    final sizes = layouts[definition.key] ?? const {};
    String binder(HomeWidgetSize size) =>
        sizes[size] == null ? 'null' : sizes[size]!;
    entries.add('''
        $key to FFHomeWidgetDefinition(
            key = $key,
            placeholder = ${kotlinString(definition.placeholder)},
            defaults = mapOf(${defaults.entries.map((e) => '${kotlinString(e.key)} to ${kotlinString(e.value)}').join(', ')}),
            small = ${binder(HomeWidgetSize.small)},
            medium = ${binder(HomeWidgetSize.medium)},
            large = ${binder(HomeWidgetSize.large)},
            provider = $provider::class.java,${_kotlinRefresh(definition.refresh, definition.refresh?.urlKeys([for (final v in definition.values) v.key]) ?? const [])}${_kotlinChoices(definition)}
        ),''');
    classes.add('''

class $provider : FFHomeWidgetProvider() {
    override val definitionKey: String = $key
}''');
  }
  return '''
// Generated by FlutterFlow from Settings > Home Screen Widgets.
package $_pkg

import android.content.Context
import android.widget.RemoteViews

$kNativeLayoutKotlinBinder
/** One widget as Settings > Home Screen Widgets defines it. */
internal class FFHomeWidgetDefinition(
    val key: String,
    /** Shown until the app first sends values. */
    val placeholder: String,
    /** The parameters' default values, as the app would send them. */
    val defaults: Map<String, String>,
    val small: FFLayoutBinder?,
    val medium: FFLayoutBinder?,
    val large: FFLayoutBinder?,
    val provider: Class<out FFHomeWidgetProvider>,
    /** What the widget fetches by itself; null when only the app updates it. */
    val refresh: FFHomeWidgetRefresh? = null,
    /** What the picker calls a choice, when a person picks one per copy. */
    val choiceTitle: String = "",
    /** The choices set in FlutterFlow. */
    val choices: List<FFHomeWidgetChoice> = emptyList(),
    /** Whether the choices the app adds are in the picker too. */
    val appChoices: Boolean = false,
) {
    /** Whether a person picks a choice for each copy they place. */
    val configurable: Boolean get() = choices.isNotEmpty() || appChoices
}

/** A choice set in FlutterFlow, and the values it sets. */
internal class FFHomeWidgetChoice(
    val id: String,
    val name: String,
    val values: Map<String, String>,
)

/** A widget fetching its own values from [url] (see FFHomeWidgetFetcher). */
internal class FFHomeWidgetRefresh(
    val url: String,
    val headers: Map<String, String>,
    val values: List<FFFetchedValue>,
    /**
     * The values the URL reads, as `{key}`. A URL that reads any is fetched
     * for each choice on its own, and stores what it fetched for that choice.
     */
    val keys: List<String> = emptyList(),
)

/**
 * One value the widget fetches: its [type] and its [path] in the response,
 * each step a field name (String) or a list position (Int).
 */
internal class FFFetchedValue(val key: String, val type: String, val path: List<Any>)

internal object FFHomeWidgetDefinitions {
    val all: Map<String, FFHomeWidgetDefinition> = mapOf(
${entries.join('\n')}
    )
}
${classes.join('\n')}
''';
}

String _kotlinPlugin() =>
    '''
package $_pkg

import android.appwidget.AppWidgetManager
import android.content.ComponentName
import android.content.Context
import android.content.Intent
import android.os.Build
import io.flutter.embedding.engine.FlutterEngine
import io.flutter.embedding.engine.plugins.FlutterPlugin
import io.flutter.embedding.engine.plugins.activity.ActivityAware
import io.flutter.embedding.engine.plugins.activity.ActivityPluginBinding
import io.flutter.embedding.engine.renderer.FlutterUiDisplayListener
import io.flutter.plugin.common.MethodCall
import io.flutter.plugin.common.PluginRegistry
import io.flutter.plugin.common.MethodChannel
import org.json.JSONArray
import org.json.JSONObject

/**
 * Method channel `$kHomeWidgetChannelName`: ${kHomeWidgetMethods.join(', ')}.
 * Generated from the channel contract; do not edit by hand.
 *
 * Stores a widget's values in SharedPreferences and redraws every copy of
 * that widget on the home screen. The widget keeps showing them after the app
 * closes.
 */
class $kHomeWidgetPluginClass :
    FlutterPlugin,
    ActivityAware,
    PluginRegistry.NewIntentListener,
    MethodChannel.MethodCallHandler {
    private var channel: MethodChannel? = null
    private var context: Context? = null
    private var engine: FlutterEngine? = null
    private var activity: ActivityPluginBinding? = null

    // --- Opening a page (FFHomeWidgetOpenActivity) -------------------------

    override fun onAttachedToActivity(binding: ActivityPluginBinding) {
        activity = binding
        binding.addOnNewIntentListener(this)
        openPage(binding.activity.intent)
    }

    override fun onReattachedToActivityForConfigChanges(binding: ActivityPluginBinding) {
        onAttachedToActivity(binding)
    }

    override fun onDetachedFromActivityForConfigChanges() {
        onDetachedFromActivity()
    }

    override fun onDetachedFromActivity() {
        activity?.removeOnNewIntentListener(this)
        activity = null
    }

    override fun onNewIntent(intent: Intent): Boolean = openPage(intent)

    /**
     * Shows the page a widget tap asked for, as a route pushed to the app's
     * router once the app draws (a route pushed earlier finds no router).
     */
    private fun openPage(intent: Intent?): Boolean {
        val location = intent?.getStringExtra(FFHomeWidgetOpenActivity.EXTRA_LOCATION) ?: return false
        // Handled once: not again when the activity is recreated.
        intent.removeExtra(FFHomeWidgetOpenActivity.EXTRA_LOCATION)
        val engine = engine ?: return false
        val renderer = engine.renderer
        if (renderer.isDisplayingFlutterUi) {
            engine.navigationChannel.pushRoute(location)
        } else {
            renderer.addIsDisplayingFlutterUiListener(object : FlutterUiDisplayListener {
                override fun onFlutterUiDisplayed() {
                    renderer.removeIsDisplayingFlutterUiListener(this)
                    engine.navigationChannel.pushRoute(location)
                }

                override fun onFlutterUiNoLongerDisplayed() {}
            })
        }
        return true
    }

    override fun onAttachedToEngine(binding: FlutterPlugin.FlutterPluginBinding) {
        context = binding.applicationContext
        @Suppress("DEPRECATION")
        engine = binding.flutterEngine
        FFHomeWidgetRenderer.publishPreviews(binding.applicationContext)
        channel = MethodChannel(binding.binaryMessenger, "$kHomeWidgetChannelName").also {
            it.setMethodCallHandler(this)
        }
    }

    override fun onDetachedFromEngine(binding: FlutterPlugin.FlutterPluginBinding) {
        channel?.setMethodCallHandler(null)
        channel = null
        context = null
        engine = null
    }

    override fun onMethodCall(call: MethodCall, result: MethodChannel.Result) {
        val ctx = context
        if (ctx == null) {
            result.error("unavailable", "Not attached", null)
            return
        }
        when (call.method) {
            "$kHomeWidgetMethodIsSupported" -> {
                result.success(true)
                return
            }
            "$kHomeWidgetMethodIsPinSupported" -> {
                result.success(
                    Build.VERSION.SDK_INT >= 26 &&
                        AppWidgetManager.getInstance(ctx)?.isRequestPinAppWidgetSupported == true,
                )
                return
            }
            "$kHomeWidgetMethodPlacedWidgets" -> {
                result.success(FFHomeWidgetRenderer.placed(ctx))
                return
            }
        }
        val key = call.argument<String>("$kHomeWidgetArgDefinitionKey")
        if (key.isNullOrEmpty()) {
            result.error("invalid_arguments", "$kHomeWidgetArgDefinitionKey is required", null)
            return
        }
        val choice = call.argument<String>("$kHomeWidgetArgChoiceId")?.takeIf { it.isNotEmpty() }
        when (call.method) {
            "$kHomeWidgetMethodUpdate" -> {
                val raw = call.argument<Map<String, Any?>>("$kHomeWidgetArgValues") ?: emptyMap()
                val values = HashMap<String, String>()
                for ((k, v) in raw) {
                    if (v is String) values[k] = v
                }
                val schedule = JSONArray()
                for (entry in call.argument<List<Map<String, Any?>>>("$kHomeWidgetArgSchedule") ?: emptyList()) {
                    val at = (entry["$kHomeWidgetScheduleAt"] as? Number)?.toLong() ?: continue
                    val scheduled = JSONObject()
                    for ((k, v) in (entry["$kHomeWidgetScheduleValues"] as? Map<*, *>) ?: emptyMap<Any, Any>()) {
                        if (k is String && v is String) scheduled.put(k, v)
                    }
